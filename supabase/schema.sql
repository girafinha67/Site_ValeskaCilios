-- Cliente cancela o próprio horário respeitando a antecedência mínima configurada
create or replace function public.cancel_my_booking(p_id uuid) returns public.bookings
language plpgsql security definer set search_path = public as $$
declare
  b public.bookings;
  hrs int := coalesce((select (value->>'cancel_hours')::int from public.settings where key = 'booking'), 24);
begin
  select * into b from public.bookings where id = p_id and client_id = auth.uid();
  if not found then raise exception 'Agendamento não encontrado'; end if;
  if b.status not in ('pendente','confirmado') then raise exception 'Este agendamento não pode mais ser cancelado'; end if;
  if b.starts_at - now() < make_interval(hours => hrs) then
    raise exception 'Cancelamentos online só até % horas antes. Fale conosco pelo WhatsApp.', hrs;
  end if;
  update public.bookings set status = 'cancelado', cancelled_by = 'cliente' where id = p_id returning * into b;
  return b;
end $$;
grant execute on function public.cancel_my_booking(uuid) to authenticated;

